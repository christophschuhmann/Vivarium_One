import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { encounterMemory, socialPerspective, perspectiveThought, socialEvidenceLabel } from '../server/living/expanded/tom-language.js';
const p = {id:'me',age:30,profile:{family:{parent_ids:[]},social:{wish:'Ich möchte gehört werden.'}},relations:{},state:{needs:{hunger:.2,fatigue:.1},psychology:{big_five:{neuroticism:.4}},affect:{states:[]}}};
const subject={name:'Robin'}, context={topic:'leisure',role:[],otherAge:31,tension:0};
const probability={support:.42,obligation:.25,criticism:.12,romance:.08,unknown:.13};
const event={id:'e1',end:3600,participants:['me','other'],facts:{category:'ask_help',outcome:'accepted'},witnesses:[]};
const source={eventId:'e1',at:3600,observed:'ask_help accepted',modality:'direct',reliability:.85};
const make=(own=p,ctx=context,mem=encounterMemory(event,ctx),sources=[source])=>socialPerspective(own,subject,ctx,probability,mem,sources);
const initiator=make();
assert.match(initiator.observation,/Ich habe den Kontakt begonnen/);
assert.match(initiator.interpretation,/meine Bitte/);
assert.match(initiator.interpretation,/noch nicht.*geleistet/);
assert.match(initiator.metabelief,/Wunsch nach Unterstützung/);
const receiving=make({...p,id:'other'},context,encounterMemory(event,context));
assert.match(receiving.observation,/Robin hat den Kontakt begonnen/);
assert.match(receiving.interpretation,/um Hilfe zu bitten/);
assert.match(receiving.metabelief,/Bereitschaft zu diesem Gespräch/);
assert.notEqual(initiator.nextStep,receiving.nextStep);
const refusal=make(p,{...context,topic:'romance'}, {...encounterMemory(event,context),category:'ask_date',outcome:'declined'},[{...source,observed:'ask_date declined'}]);
assert.match(refusal.interpretation,/Grenze steht fest/);
assert.match(refusal.nextStep,/dränge nicht/);
assert.ok(!refusal.nextStep.includes('später'));
const telephone=make(p,context,{...encounterMemory(event,context),remote:true});
assert.match(telephone.observation,/Mimik.*nicht sehen/);
assert.match(telephone.audience,/ungestört/);
const witness=make(p,context,{...encounterMemory(event,context),witness:true,audience:2});
assert.equal(witness.metabelief,null);
assert.match(witness.observation,/nicht ihr Gegenüber/);
assert.ok(witness.alternatives.every(x=>x.kind!=='romance'));
assert.match(witness.interpretation,/nicht ein Angebot oder Interesse an mir/);
assert.ok(witness.alternatives.every(x=>!x.text.includes('mit mir abstimmen')));
const hungry=make({...p,state:{...p.state,needs:{hunger:.9,fatigue:.85}}});
assert.equal(hungry.selfLens.length,2);
assert.match(hungry.selfLens.join(' '),/Hunger.*Müdigkeit/);
assert.deepEqual(hungry.alternatives,initiator.alternatives,'Current self-lens must not fabricate new evidence');
assert.match(make(p,{...context,topic:'work',explicitManager:true},{category:'coordinate_work'}).alternatives.find(x=>x.kind==='obligation').text,/bekannte Führungskraft/);
assert.match(make(p,{...context,topic:'work',explicitManager:false},{category:'coordinate_work'}).alternatives.find(x=>x.kind==='obligation').text,/nicht automatisch eine Weisung/);
assert.match(make({...p,age:10},{...context,topic:'family',isChild:true},{category:'small_talk'}).alternatives.find(x=>x.kind==='obligation').text,/überschaubare Aufgabe/);
assert.match(make(p,{...context,topic:'family',isParent:true},{category:'small_talk'}).alternatives.find(x=>x.kind==='obligation').text,/Mitbestimmung/);
assert.match(make(p,{...context,partner:true},{category:'small_talk'}).alternatives.find(x=>x.kind==='obligation').text,/gemeinsame Ausgaben/);
for(const [age,otherAge,allowed] of [[10,10,false],[13,14,false],[14,15,true],[14,16,false],[17,18,false],[18,17,false],[18,18,true]]) {
 const v=make({...p,age},{...context,otherAge});
 assert.equal(v.alternatives.some(a=>a.kind==='romance'),false,'Romance below top 3 is not displayed');
 const romanceFirst = socialPerspective({...p,age},subject,{...context,otherAge},{romance:.7,support:.2,unknown:.1},encounterMemory(event,context),[source]);
 assert.equal(romanceFirst.alternatives.some(a=>a.kind==='romance'),allowed,`${age}/${otherAge}`);
}
assert.ok(!socialPerspective(p,subject,{...context,role:['Schwester']},{romance:.7,support:.2,unknown:.1},encounterMemory(event,context),[source]).alternatives.some(a=>a.kind==='romance'));
assert.match(make(p,context,{},[]).observation,/Noch keine eigene Begegnung/);
assert.match(make(p,context,{},[source]).observation,/nicht festgehalten/);
assert.match(make(p,context,{...encounterMemory(event,context),category:'gossip'}).unknowns.join(' '),/keine bestätigten Tatsachen/);
assert.match(make(p,context,{category:'apologize'}).nextStep,/eigenen Anteil/);
assert.match(make(p,context,{category:'confide'}).nextStep,/unter uns/);
assert.match(make(p,context,{category:'debate'}).alternatives.find(a=>a.kind==='criticism')?.text || make(p,context,{category:'debate'}).nextStep,/Argument/);
assert.match(make(p,context,{category:'tease'}).nextStep,/zu weit/);
assert.match(socialEvidenceLabel(source),/Bitte um Hilfe · Kontakt angenommen/);
assert.ok(!perspectiveThought(initiator).includes('Eine weitere Möglichkeit: möchte'));
// Reading old saves must update presentation only, without rewriting memories,
// learned probabilities, money, time, or another person's secrets.
const scratch=fs.mkdtempSync(path.join(os.tmpdir(),'tom-language-'));
process.env.VIV_DATA_DIR=scratch;process.env.VIV_SECRET='tom-presentation-test';
try {
 const {socialMindContext}=await import('../server/living/expanded/tom.js');
 const legacy=structuredClone(p);
 legacy.state.social_cognition={contacts:{other:{subjectId:'other',subjectName:'Robin',knownRoles:['Freund'],updatedAt:3600,topics:{leisure:{topic:'leisure',thought:'Eine alte Gedankenformulierung.',probabilities:probability,sourceRefs:[source],updatedAt:3600}}}},metabeliefs:{other:{subjectId:'other',eventId:'e1',text:'Ein veralteter falscher Eindruck.',depth:2,confidence:.45}}};
 const before=JSON.stringify(legacy);
 const first=socialMindContext(legacy);
 assert.equal(JSON.stringify(legacy),before);
 assert.ok(first.contacts[0].topics.leisure.perspective);
 assert.match(first.secondOrder[0].text,/älteren Kontakt/);
 assert.equal(first.secondOrder[0].depth,2);
 assert.match(first.contacts[0].topics.leisure.sourceRefs[0].description,/Bitte um Hilfe/);
 legacy.state.needs.hunger=.9;
 const second=socialMindContext(legacy);
 assert.match(second.contacts[0].topics.leisure.thought,/Hunger/);
 assert.deepEqual(first.contacts[0].topics.leisure.sourceRefs,second.contacts[0].topics.leisure.sourceRefs);
 assert.deepEqual(first.contacts[0].topics.leisure.probabilities,second.contacts[0].topics.leisure.probabilities);
} finally { fs.rmSync(scratch,{recursive:true,force:true}); }
console.log('PASS social perspectives: direction, context, refusal, witness, telephone, age safety, own needs, legacy read-only views.');
