#!/usr/bin/env python3
"""Build the final, complete, human-and-machine-readable results file for the
narrator TTS experiment (prompts + voices + temperature), including every
individual judged sample with its reasoning. Also emits the HTML section."""
import json, os
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = os.path.join(ROOT, "scripts")

main = json.load(open(os.path.join(S, "tts_experiment_results.json")))
confirm = json.load(open(os.path.join(S, "tts_experiment_phase3_confirm.json")))
temp_sweep = json.load(open(os.path.join(S, "tts_experiment_phase4_temperature.json")))
temp_more = json.load(open(os.path.join(S, "tts_experiment_phase4b_iapetus_t03.json")))

PROMPTS = main["phase1_results"][0]["style"] and {r["label"]: r["style"] for r in main["phase1_results"]}

# ---------- Phase 1: prompt ranking (as tested, single batch of 3 samples each) ----------
phase1 = []
for r in sorted(main["phase1_results"], key=lambda r: -(r.get("score") or -1)):
    phase1.append({
        "label": r["label"],
        "prompt_text": r["style"],
        "voice_used": main["phase1_fixed_voice"],
        "avg_score": r.get("score"),
        "min_score": r.get("score_min"),
        "max_score": r.get("score_max"),
        "n_samples": r.get("n_scored"),
        "raw_scores": [s.get("score") for s in r.get("samples", [])],
        "vocal_bursts_ever_detected": r.get("vocal_bursts_detected"),
        "judge_reasoning_per_sample": [s.get("reasoning") for s in r.get("samples", [])],
    })
winning_prompt_label = main["best_prompt_label"]
winning_prompt_text = main["best_prompt_text"]

# ---------- Phase 2 + confirmation: pool all raw draws per voice at temp=1.0 ----------
by_voice_samples = defaultdict(list)  # voice -> list of {score, reasoning, vocal_bursts_detected}
for r in main["phase2_results"]:
    for s in r.get("samples", []):
        if isinstance(s.get("score"), (int, float)):
            by_voice_samples[r["voice"]].append(s)
for r in confirm:
    for s in r.get("samples", []):
        if isinstance(s.get("score"), (int, float)):
            by_voice_samples[r["voice"]].append(s)

MALE_VOICE_STYLES = {
    "Algenib": "Gravelly", "Charon": "Informative", "Orus": "Firm", "Schedar": "Even",
    "Iapetus": "Clear", "Umbriel": "Easy-going", "Rasalgethi": "Informative",
    "Achird": "Friendly", "Sadaltager": "Knowledgeable", "Zubenelgenubi": "Casual",
}

phase2 = []
for voice, samples in by_voice_samples.items():
    scores = [s["score"] for s in samples]
    hits = sum(1 for x in scores if x >= 7)
    phase2.append({
        "voice": voice,
        "voice_style_tag": MALE_VOICE_STYLES.get(voice, ""),
        "prompt_used": winning_prompt_label,
        "temperature": 1.0,
        "n_samples": len(scores),
        "avg_score": round(sum(scores) / len(scores), 2),
        "hit_rate_pct": round(hits / len(scores) * 100, 1),
        "raw_scores": scores,
        "vocal_bursts_ever_detected": any(s.get("vocal_bursts_detected") for s in samples),
        "judge_reasoning_per_sample": [s.get("reasoning") for s in samples],
    })
phase2.sort(key=lambda r: -r["hit_rate_pct"])
winning_voice = phase2[0]["voice"]

# ---------- Phase 4: temperature sweep ----------
by_vt = defaultdict(list)
for r in temp_sweep:
    if isinstance(r.get("score"), (int, float)):
        by_vt[(r["voice"], r.get("temperature"))].append(r)
for r in temp_more:
    if isinstance(r.get("score"), (int, float)):
        by_vt[("Iapetus", 0.3)].append(r)

phase4 = []
for (voice, temp), samples in by_vt.items():
    scores = [s["score"] for s in samples]
    hits = sum(1 for x in scores if x >= 7)
    phase4.append({
        "voice": voice, "temperature": temp, "prompt_used": winning_prompt_label,
        "n_samples": len(scores), "avg_score": round(sum(scores) / len(scores), 2),
        "hit_rate_pct": round(hits / len(scores) * 100, 1) if scores else None,
        "raw_scores": scores,
    })
# add the temp=1.0 rows for the same voices for direct comparison
for voice in set(v for v, _ in by_vt):
    if voice in by_voice_samples:
        scores = [s["score"] for s in by_voice_samples[voice]]
        hits = sum(1 for x in scores if x >= 7)
        phase4.append({
            "voice": voice, "temperature": 1.0, "prompt_used": winning_prompt_label,
            "n_samples": len(scores), "avg_score": round(sum(scores) / len(scores), 2),
            "hit_rate_pct": round(hits / len(scores) * 100, 1), "raw_scores": scores,
        })
phase4.sort(key=lambda r: (r["voice"], r["temperature"]))

result = {
    "experiment": "Vivarium narrator TTS quality search",
    "date": "2026-07-02",
    "method": (
        "Every audio sample was generated by gemini-3.1-flash-tts and judged by "
        "gemini-3.5-flash (given the audio as multimodal input) on a strict 0-10 "
        "rubric: does this sound like a calm, professional audiobook narrator "
        "PLAINLY READING the text, as opposed to an actor PERFORMING it. Scores "
        "<=3 required an audible vocal burst (laugh/gasp/sigh) or clear acting. "
        "Because gemini-3.1-flash-tts runs at temperature=1 by default, each "
        "(prompt, voice) combination was sampled multiple independent times — a "
        "single sample is not reliable evidence, since the SAME prompt+voice can "
        "swing from a perfect reading to an over-acted one on different draws."
    ),
    "narration_text_under_test": main["narration_text"],
    "judge_model": "gemini-3.5-flash",
    "tts_model": "gemini-3.1-flash-tts",
    "phase1_prompt_search": {
        "description": "5 narration-direction prompts tested, voice held constant (Algenib), 3 samples each.",
        "results": phase1,
        "winner": {"label": winning_prompt_label, "prompt_text": winning_prompt_text},
    },
    "phase2_voice_search": {
        "description": (
            "10 male voices tested with the Phase-1 winning prompt at default temperature (1.0). "
            "All independent draws (initial batch of 3 + a confirmation batch of up to 5 more for "
            "the top 2) are pooled per voice into a single true hit-rate, since 3-sample averages "
            "alone proved unreliable (see caveat)."
        ),
        "results": phase2,
        "winner": {"voice": winning_voice, "hit_rate_pct": phase2[0]["hit_rate_pct"], "n_samples": phase2[0]["n_samples"]},
    },
    "phase3_temperature_sweep": {
        "description": (
            "Tested whether lowering TTS temperature below the default 1.0 improves reliability, "
            "for the two leading voices with the winning prompt. Small sample sizes on some cells "
            "(some batches hit API rate-limit timeouts under this session's heavy concurrent load)."
        ),
        "results": phase4,
        "finding": "No evidence that lowering temperature helps; Iapetus scored WORSE at 0.3 (67%) and 0.6 (50%) than at the default 1.0 (87.5%). Temperature left at the default.",
    },
    "final_recommendation": {
        "voice": winning_voice,
        "prompt_label": winning_prompt_label,
        "prompt_text": winning_prompt_text,
        "temperature": 1.0,
        "hit_rate_pct": phase2[0]["hit_rate_pct"],
        "n_samples": phase2[0]["n_samples"],
        "caveat": (
            "Not 100% reliable — roughly 1 in 8 draws with the winning combination still produced "
            "an audible vocal burst or over-acted delivery. This appears to be inherent TTS model "
            "randomness at temperature=1, not fixable by prompt/voice/temperature choice alone. "
            "The prior default (Algenib + old prompt) scored 0% (0/3) by comparison."
        ),
        "applied_in_code": [
            "web/app.js — DEFAULT_NARRATOR_STYLE constant and ttsPrefs() default narrator voice",
            "server/video_export.js — narrator voice + style for exported videos",
            "config/gemini_tts_voices.json — vivarium_casting.narrator",
        ],
    },
}

out_path = os.path.join(ROOT, "config", "narrator_tts_experiment.json")
json.dump(result, open(out_path, "w"), indent=2)
print(f"wrote {out_path}")
print(f"winning prompt: {winning_prompt_label}")
print(f"winning voice: {winning_voice} ({phase2[0]['hit_rate_pct']}% hit rate, n={phase2[0]['n_samples']})")
